-- 0025 · 回复可以回「某一条回复」
--
-- 结构上**仍然只有一层**：所有回复的 `parent_id` 都指向主楼，
-- 想回复哪一条只记在 `reply_to_id` 里。
--
-- 为什么不做成真正的树：
--   1. 楼的层数一深，窄屏上缩进就没地方了（一屏宽度只够两级）；
--   2. 渲染要递归、删除要级联、后台要重新画树；
--   3. 大家实际在用的（GitHub / Discourse）都是**平铺 + @某人**，
--      读起来是对话顺序，比越缩越窄的树清楚。
-- 所以这里只补一个「回到谁」的指针，渲染层用 @ 表达。
--
-- 软删的回复如果被指着，渲染时找不到名字就退回主楼作者（见 toEntry）。
ALTER TABLE comments ADD COLUMN reply_to_id INTEGER;
